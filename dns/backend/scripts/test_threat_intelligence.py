    print("====================================================================")
    print(f"Domain: {d}")
    print()
    print("Normalization")
    print(f"├── FQDN:              {norm['fqdn']}")
    print(f"├── Registered domain: {norm['registered_domain']}")
    print(f"└── TLD / Subdomain:   .{norm['tld']} (Sub: {norm['subdomain'] or 'None'})")
    print()
    print("Local Intelligence")
    print(f"├── URLhaus:           {local['urlhaus']['status']} [{local['urlhaus']['classification']}]")
    print(f"└── Tranco:            {local['tranco']['status']} [{local['tranco']['classification']}]")
    print()
    print("External Intelligence")
    if not prs:
        print(f"└── Status:            {ext_tag}")
    else:
        for i, pr in enumerate(prs):
            prefix = "└──" if i == len(prs) - 1 else "├──"
            if pr.unavailable:
                res_str = f"PROVIDER FAILURE ({pr.error})"
            elif not pr.found:
                res_str = "NO_DATA (404 / 0 pulses)"
            elif pr.malicious:
                res_str = f"MALICIOUS (hits={pr.malicious_count}, conf={pr.confidence:.2f})"
            else:
                res_str = f"CLEAN (harmless={pr.harmless_count}, conf={pr.confidence:.2f})"
            print(f"{prefix} {pr.provider:<16s}: {res_str} [{ext_tag}]")
    print()
    print("Correlation")
    print(f"├── Verdict:           {inv['final_verdict']}")
    print(f"├── Risk Score:        {dec.score:.2f} (Threshold: {dec.threshold:.2f})")
    print(f"├── Confidence:        {dec.confidence:.2f}")
    print(f"└── Reason:            {inv['reason']}")
    print()
    print("Persistence & Dashboard Delivery")
    print(f"├── PostgreSQL:        {'✓ (Stored)' if pers['postgresql_reputation'] else '○ (Not required/absent)'}")
    print(f"├── SQLite Read Model: {'✓ (Aggregated)' if pers['sqlite_dashboard_db'] else '○ (Pending next aggregation)'}")
    print(f"└── API / Dashboard:   ✓ (Consumable schema)")
    print("====================================================================")
    print()


