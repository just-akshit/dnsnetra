def main() -> int:
    parser = argparse.ArgumentParser(
        description="DNS Threat Intelligence Functional Verification Tool"
    )
    parser.add_argument(
        "--domain",
        type=str,
        help="Domain to investigate through the full pipeline",
    )
    parser.add_argument(
        "--matrix",
        action="store_true",
        help="Execute controlled functional test matrix (Tests A through G + Golden)",
    )
    parser.add_argument(
        "--golden",
        type=str,
        default="google.com",
        help="Generate golden investigation tree for a specific domain",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Output raw JSON response for frontend contract validation",
    )

    args = parser.parse_args()

    investigator = ThreatIntelligenceInvestigator()

    if args.matrix:
        success = run_controlled_matrix(investigator)
        return 0 if success else 1

    if args.domain:
        inv = investigator.investigate(args.domain)
        if args.json:
            # Format JSON shape consumable by dashboard / API clients
            output = {
                "domain": inv["domain"],
                "verdict": inv["final_verdict"],
                "score": inv["decision"].score,
                "confidence": inv["decision"].confidence,
                "providers": [
                    {
                        "name": r.provider,
                        "malicious": r.malicious,
                        "confidence": r.confidence,
                        "malicious_count": r.malicious_count,
                        "harmless_count": r.harmless_count,
                        "unavailable": r.unavailable,
                        "found": r.found,
                        "error": r.error,
                        "classification": inv["external_tag"],
                    }
                    for r in inv["provider_results"]
                ],
                "local": inv["local"],
                "reason": inv["reason"],
                "persistence": {
                    "postgresql": inv["persistence"]["postgresql_reputation"],
                    "sqlite": inv["persistence"]["sqlite_dashboard_db"],
                },
                "checked_at": datetime.now(timezone.utc).isoformat(),
            }
            print(json.dumps(output, indent=2))
        else:
            print_investigation_report(inv)
        return 0

    # Default to golden investigation
    inv = investigator.investigate(args.golden)
    print_golden_investigation(inv)
    return 0


if __name__ == "__main__":
    sys.exit(main())
