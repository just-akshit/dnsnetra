# Investigation Engine
# ---------------------------------------------------------------------------
class ThreatIntelligenceInvestigator:
    def __init__(self, config: Optional[LabelingConfig] = None):
        self.config = config or LabelingConfig()
        self.online_config = self.config.get_online_ti_config()

    def evaluate_local(self, norm: Dict[str, str]) -> Dict[str, Any]:
        """Evaluate domain against local intelligence sources with scope preservation."""
        fqdn = norm["fqdn"]
        reg = norm["registered_domain"]
        
        # STEP 1 — EXACT FQDN MALICIOUS MATCH (URLhaus)
        if fqdn and fqdn != reg and is_malicious(fqdn):
            return {
                "verdict": "KNOWN_MALICIOUS",
                "source": "LOCAL (URLhaus)",
                "match_scope": "EXACT_FQDN",
                "matched_domain": fqdn,
                "tranco": {"matched": False, "status": "NO_DATA", "classification": "LOCAL"},
                "urlhaus": {"matched": True, "status": "KNOWN_MALICIOUS (EXACT_FQDN)", "classification": "LOCAL"},
            }

        # STEP 2 — TRANCO POPULARITY CONTEXT
        tranco_match = (reg and is_trusted(reg)) or (fqdn and is_trusted(fqdn))
        if tranco_match:
            is_root_art = (fqdn == reg and is_malicious(reg))
            scope = "ROOT_ARTIFACT" if is_root_art else "POPULARITY_CONTEXT"
            return {
                "verdict": "POPULAR_BENIGN_CONTEXT",
                "source": "LOCAL (Tranco)",
                "match_scope": scope,
                "matched_domain": reg or fqdn,
                "tranco": {"matched": True, "status": "POPULARITY_CONTEXT (TRANCO_MATCH)", "classification": "LOCAL"},
                "urlhaus": {"matched": is_root_art, "status": "SUPPRESSED_ROOT_ARTIFACT" if is_root_art else "NO_DATA", "classification": "LOCAL"},
            }

        # STEP 3 — UNTRUSTED REGISTERED DOMAIN FALLBACK (URLhaus)
        if reg and is_malicious(reg):
            scope = "EXACT_FQDN" if fqdn == reg else "REGISTERED_DOMAIN"
            return {
                "verdict": "KNOWN_MALICIOUS",
                "source": "LOCAL (URLhaus)",
                "match_scope": scope,
                "matched_domain": reg,
                "tranco": {"matched": False, "status": "NO_DATA", "classification": "LOCAL"},
                "urlhaus": {"matched": True, "status": f"KNOWN_MALICIOUS ({scope})", "classification": "LOCAL"},
            }

        # STEP 4 — UNKNOWN
        return {
            "verdict": "UNKNOWN",
            "source": "NO_DATA",
            "match_scope": None,
            "matched_domain": None,
            "tranco": {"matched": False, "status": "NO_DATA", "classification": "LOCAL"},
            "urlhaus": {"matched": False, "status": "NO_DATA", "classification": "LOCAL"},
        }

    def evaluate_external_live(self, domain: str) -> List[ThreatProviderResult]:
        """Perform live queries to configured external providers."""
        results: List[ThreatProviderResult] = []

        # VirusTotal
        vt = VirusTotalProvider(self.online_config)
        if vt.is_enabled():
            try:
                vt_res = vt.lookup(domain)
                results.append(vt_res)
            except Exception as exc:
                results.append(
                    ThreatProviderResult(
                        provider="VirusTotal",
                        unavailable=True,
                        error=str(exc),
                    )
                )
            finally:
                vt.close()

        # AlienVault OTX
        otx = AlienVaultOTXProvider(self.online_config)
        if otx.is_enabled():
            try:
                otx_res = otx.lookup(domain)
                results.append(otx_res)
            except Exception as exc:
                results.append(
                    ThreatProviderResult(
                        provider="AlienVault OTX",
                        unavailable=True,
                        error=str(exc),
                    )
                )
            finally:
                otx.close()

        return results

    def correlate(
        self,
        domain: str,
        provider_results: List[ThreatProviderResult],
    ) -> ThreatDecision:
        """Run correlation engine over provider results."""
        weights = {
            "VirusTotal": float(self.online_config.get("WEIGHT_VT", 0.60)),
            "AlienVault OTX": float(self.online_config.get("WEIGHT_OTX", 0.40)),
        }
        scorer = WeightedScorer(
            weights=weights,
            threshold=float(self.online_config.get("MALICIOUS_THRESHOLD", 0.60)),
        )
        score, confidence, is_malicious = scorer.calculate(provider_results)

        return ThreatDecision(
            domain=domain,
            malicious=is_malicious,
            score=score,
            confidence=confidence,
            threshold=scorer.threshold,
            provider_results=provider_results,
        )

    def check_persistence(self, domain: str) -> Dict[str, Any]:
        """Check presence of domain across PostgreSQL and SQLite read models."""
        pg_reputation = False
        pg_data = None
        try:
            pg_data = get_reputation_domain(domain)
            pg_reputation = pg_data is not None
        except Exception:
            pg_reputation = False

        # SQLite dashboard.db check
        sqlite_details = False
        sqlite_row = None
        if DASHBOARD_DB_PATH.exists():
            try:
                conn = sqlite3.connect(str(DASHBOARD_DB_PATH))
                conn.row_factory = sqlite3.Row
                cur = conn.cursor()
                cur.execute("SELECT * FROM domain_details WHERE domain = ?", (domain,))
                row = cur.fetchone()
                if row:
                    sqlite_details = True
                    sqlite_row = dict(row)
                conn.close()
            except Exception:
                sqlite_details = False

        return {
            "postgresql_reputation": pg_reputation,
            "postgresql_data": pg_data,
            "sqlite_dashboard_db": sqlite_details,
            "sqlite_data": sqlite_row,
        }

    def investigate(
        self,
        domain: str,
        override_provider_results: Optional[List[ThreatProviderResult]] = None,
        fixture_tag: Optional[str] = None,
        force_external: bool = False,
    ) -> Dict[str, Any]:
        """Execute full investigation on a domain with evidence scope."""
        start_time = time.perf_counter()
        norm = normalize_domain(domain)
        local_res = self.evaluate_local(norm)

        # External TI: skipped if local match is authoritative (unless forced or overridden)
        if override_provider_results is not None:
            provider_results = override_provider_results
            ext_tag = fixture_tag or "MOCK / FIXTURE"
        elif local_res["verdict"] in ("KNOWN_MALICIOUS", "POPULAR_BENIGN_CONTEXT") and not force_external:
            provider_results = []
            ext_tag = "SKIPPED (Local Authoritative Match)"
        else:
            provider_results = self.evaluate_external_live(norm["fqdn"])
            ext_tag = "REAL"

        # Correlation
        decision = self.correlate(norm["fqdn"], provider_results)

        # Derive final human verdict & scope
        if local_res["verdict"] == "KNOWN_MALICIOUS":
            final_verdict = "KNOWN_MALICIOUS"
            verdict_source = local_res["source"]
            verdict_scope = local_res["match_scope"]
            reason = f"Listed in URLhaus malware database (Scope: {verdict_scope}, Matched: {local_res['matched_domain']})"
        elif decision.malicious:
            final_verdict = "KNOWN_MALICIOUS"
            verdict_source = f"EXTERNAL ({ext_tag})"
            verdict_scope = "CORRELATED"
            reason = f"Correlated score ({decision.score:.2f}) exceeds threshold ({decision.threshold:.2f})"
        elif local_res["verdict"] == "POPULAR_BENIGN_CONTEXT":
            final_verdict = "POPULAR_BENIGN_CONTEXT"
            verdict_source = "LOCAL (Tranco)"
            verdict_scope = local_res["match_scope"]
            reason = f"Top-ranked global domain in Tranco database (Scope: {verdict_scope})"
        elif decision.has_intelligence and not decision.malicious:
            final_verdict = "KNOWN_CLEAN"
            verdict_source = f"EXTERNAL ({ext_tag})"
            verdict_scope = "EXTERNAL_PROVIDER"
            reason = "Queried across threat providers with zero malicious signals"
        else:
            final_verdict = "REVIEW_NEEDED / UNKNOWN"
            verdict_source = "INCONCLUSIVE"
            verdict_scope = "LEGACY / UNKNOWN"
            reason = "No authoritative local or external intelligence found"

        # Persistence check
        persist_status = self.check_persistence(norm["fqdn"])

        duration_ms = (time.perf_counter() - start_time) * 1000.0

        return {
            "domain": norm["fqdn"],
            "normalization": norm,
            "local": local_res,
            "external_tag": ext_tag,
            "provider_results": provider_results,
            "decision": decision,
            "final_verdict": final_verdict,
            "verdict_source": verdict_source,
            "verdict_scope": verdict_scope,
            "reason": reason,
            "persistence": persist_status,
            "duration_ms": duration_ms,
        }


