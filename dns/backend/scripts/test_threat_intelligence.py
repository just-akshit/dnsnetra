    print_investigation_report(inv_d_mock)
    pass_d_mock = inv_d_mock["decision"].malicious and inv_d_mock["external_tag"] == "MOCK / FIXTURE"
    print(f"  Result D.2 (MOCK / FIXTURE): {'PASS' if pass_d_mock else 'FAIL'}\n")
    if not (pass_d_real or pass_d_mock): matrix_passed = False

