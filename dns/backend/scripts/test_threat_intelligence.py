# ---------------------------------------------------------------------------
# Normalization Helper
# ---------------------------------------------------------------------------
def normalize_domain(raw_domain: str) -> Dict[str, str]:
    """Normalize a domain string and extract registered domain and TLD."""
    cleaned = raw_domain.strip().lower().rstrip(".")
    ext = tldextract.extract(cleaned)
    registered_domain = (
        getattr(ext, "top_domain_under_public_suffix", None)
        or getattr(ext, "registered_domain", "")
        or cleaned
    )
    tld = ext.suffix
    subdomain = ext.subdomain
    return {
        "fqdn": cleaned,
        "registered_domain": registered_domain,
        "tld": tld,
        "subdomain": subdomain,
    }


